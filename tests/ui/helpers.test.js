const vm=require('vm'),fs=require('fs');
const ctx={window:{__NO_BOOT__:true,matchMedia:()=>({matches:false})},document:{querySelector:()=>({content:'tok'}),createElement:()=>({}),getElementById:()=>({}),documentElement:{setAttribute(){}}},localStorage:{getItem:()=>null,setItem(){}},console,Date,JSON,Object,Array,Math,parseInt,isNaN,String,Number,RegExp,URLSearchParams,setTimeout,clearTimeout};
ctx.window.window=ctx.window; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(require('path').join(__dirname,'..','..','web','app.js'),'utf8'),ctx);
const U=ctx.window.TGU; const assert=require('assert');
const now=new Date('2026-10-24T12:00:00');
assert.strictEqual(U.fmtTime('2026-10-24T09:05:00',now),'09:05');
assert.strictEqual(U.fmtTime('2026-10-22T09:05:00',now),'Thu');
assert.strictEqual(U.fmtTime('2025-01-03T09:05:00',now),'3 Jan 2025');
assert.strictEqual(U.fmtDay('2026-10-23T09:05:00',now),'Yesterday');
assert.strictEqual(U.fmtDay('2026-10-24T01:00:00',now),'Today');
assert.strictEqual(U.initials('Lisa Kumar'),'LK'); assert.strictEqual(U.initials(''),'?'); assert.strictEqual(U.initials('राहुल'),'र');
assert.strictEqual(U.humanSize(1536),'1.5 KB'); assert.strictEqual(U.humanSize(10),'10 B');
const parts=U.linkify('see https://a.com/x?y=1, and http://b.org. ok');
assert.deepStrictEqual(Array.from(parts,p=>p.t+':'+p.v),['text:see ','url:https://a.com/x?y=1','text:, and ','url:http://b.org','text:. ok']);
assert.deepStrictEqual(Array.from(U.linkify('<script>alert(1)</script>'),p=>p.t),['text']);
const m=U.mergeMessages([{id:1,text:'a'},{id:3}],[{id:2},{id:3,text:'edited'}]);
